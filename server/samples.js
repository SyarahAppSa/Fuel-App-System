// مولدات ملفات تجريبية (PDF مستند نموذجي + صور PNG) — للبيانات التجريبية والاختبارات فقط
import zlib from 'node:zlib';

/** PDF نصي بسيط صالح (صفحة واحدة، خط Helvetica) */
export function makePdf(lines) {
  const esc = (s) => s.replace(/\\/g, '\\\\').replace(/\(/g, '\\(').replace(/\)/g, '\\)');
  const content = ['BT', '/F1 13 Tf', '50 780 Td', '18 TL', ...lines.map((l) => `(${esc(l)}) Tj T*`), 'ET'].join('\n');
  const objs = [
    '<< /Type /Catalog /Pages 2 0 R >>',
    '<< /Type /Pages /Kids [3 0 R] /Count 1 >>',
    '<< /Type /Page /Parent 2 0 R /MediaBox [0 0 595 842] /Resources << /Font << /F1 4 0 R >> >> /Contents 5 0 R >>',
    '<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>',
    `<< /Length ${Buffer.byteLength(content)} >>\nstream\n${content}\nendstream`,
  ];
  let out = '%PDF-1.4\n';
  const offs = [];
  objs.forEach((o, i) => { offs.push(Buffer.byteLength(out)); out += `${i + 1} 0 obj\n${o}\nendobj\n`; });
  const xref = Buffer.byteLength(out);
  out += `xref\n0 ${objs.length + 1}\n0000000000 65535 f \n` + offs.map((o) => String(o).padStart(10, '0') + ' 00000 n \n').join('');
  out += `trailer\n<< /Size ${objs.length + 1} /Root 1 0 R >>\nstartxref\n${xref}\n%%EOF\n`;
  return Buffer.from(out, 'latin1');
}

export function sampleAramcoPdf({ docNumber, lpCode, lpName, product = 'Diesel', liters, issue, valid }) {
  return makePdf([
    'SAMPLE FUEL LIFTING AUTHORIZATION - DEMO ONLY',
    'Generated by Fuel App test data. Not an official document.',
    '',
    `Document No: ${docNumber}`,
    `Loading Point: ${lpName} (${lpCode})`,
    `Product: ${product}`,
    `Quantity: ${Number(liters).toLocaleString('en-US')} Liters`,
    `Issue Date: ${issue}`,
    `Valid Until: ${valid}`,
    '',
    'Customer: DEMO CUSTOMER',
  ]);
}

/** صورة PNG تجريبية بلون وخطوط تميز نوع اللقطة */
export function makePng(w = 320, h = 220, [r, g, b] = [194, 65, 12]) {
  const raw = Buffer.alloc((w * 3 + 1) * h);
  for (let y = 0; y < h; y++) {
    raw[y * (w * 3 + 1)] = 0;
    for (let x = 0; x < w; x++) {
      const i = y * (w * 3 + 1) + 1 + x * 3;
      const stripe = ((x + y) >> 4) % 2 ? 1 : 0.85;
      const shade = 0.6 + 0.4 * (1 - y / h);
      raw[i] = Math.min(255, r * stripe * shade + 30); raw[i + 1] = Math.min(255, g * stripe * shade + 30); raw[i + 2] = Math.min(255, b * stripe * shade + 30);
    }
  }
  const crcTable = Array.from({ length: 256 }, (_, n) => { let c = n; for (let k = 0; k < 8; k++) c = c & 1 ? 0xedb88320 ^ (c >>> 1) : c >>> 1; return c >>> 0; });
  const crc = (buf) => { let c = 0xffffffff; for (const x of buf) c = crcTable[(c ^ x) & 0xff] ^ (c >>> 8); return (c ^ 0xffffffff) >>> 0; };
  const chunk = (type, data) => { const len = Buffer.alloc(4); len.writeUInt32BE(data.length); const td = Buffer.concat([Buffer.from(type), data]); const c = Buffer.alloc(4); c.writeUInt32BE(crc(td)); return Buffer.concat([len, td, c]); };
  const ihdr = Buffer.alloc(13); ihdr.writeUInt32BE(w, 0); ihdr.writeUInt32BE(h, 4); ihdr[8] = 8; ihdr[9] = 2; ihdr[10] = 0; ihdr[11] = 0; ihdr[12] = 0;
  return Buffer.concat([Buffer.from([0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a]), chunk('IHDR', ihdr), chunk('IDAT', zlib.deflateSync(raw)), chunk('IEND', Buffer.alloc(0))]);
}

